  #_ REGISTER_OUT r4 0x10001010
  #_ REGISTER_OUT r30 0x80000003
  #_ REGISTER_OUT r31 0x00000004

test_lmw_stmw_roundtrip:
  #_ MEMORY_IN 10001040 00000000 00000000 00000000
  #_ REGISTER_IN r3 0x10001040
  #_ REGISTER_IN r29 0x11111111
  #_ REGISTER_IN r30 0x22222222
  #_ REGISTER_IN r31 0x33333333
  stmw r29, 0(r3)
  li r29, 0
  li r30, 0
  li r31, 0
  lmw r29, 0(r3)
  blr
  #_ REGISTER_OUT r29 0x11111111
  #_ REGISTER_OUT r30 0x22222222
  #_ REGISTER_OUT r31 0x33333333
  #_ MEMORY_OUT 10001040 11111111 22222222 33333333
