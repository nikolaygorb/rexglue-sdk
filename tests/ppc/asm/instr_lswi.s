test_lswi_7:
  #_ MEMORY_IN 10001000 11223344 55667788
  #_ REGISTER_IN r3 0x10001000
  #_ REGISTER_IN r6 0xFFFFFFFFFFFFFFFF
  lswi r5, r3, 7
  blr
  #_ REGISTER_OUT r3 0x10001000
  #_ REGISTER_OUT r5 0x11223344
  #_ REGISTER_OUT r6 0x55667700

test_lswi_wraps_to_r0:
  #_ MEMORY_IN 10001000 AABBCCDD 01020304
  #_ REGISTER_IN r4 0x10001000
  lswi r31, r4, 8
  blr
  #_ REGISTER_OUT r4 0x10001000
  #_ REGISTER_OUT r31 0xAABBCCDD
  #_ REGISTER_OUT r0 0x01020304

test_lswi_one_byte:
  #_ MEMORY_IN 10001000 99000000
  #_ REGISTER_IN r3 0x10001000
  #_ REGISTER_IN r5 0xFFFFFFFFFFFFFFFF
  lswi r5, r3, 1
  blr
  #_ REGISTER_OUT r5 0x99000000
