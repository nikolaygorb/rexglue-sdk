test_stdbrx_1:
  #_ MEMORY_IN 10001000 CCCCCCCC CCCCCCCC CCCCCCCC CCCCCCCC
  #_ REGISTER_IN r3 0x0123456789ABCDEF
  #_ REGISTER_IN r4 0x10001000
  #_ REGISTER_IN r5 4
  stdbrx r3, r4, r5
  blr
  #_ REGISTER_OUT r3 0x0123456789ABCDEF
  #_ MEMORY_OUT 10001000 CCCCCCCC EFCDAB89 67452301 CCCCCCCC

test_stdbrx_ra0:
  #_ MEMORY_IN 10001010 CCCCCCCC CCCCCCCC CCCCCCCC
  #_ REGISTER_IN r3 0x8000000000000001
  #_ REGISTER_IN r5 0x10001010
  stdbrx r3, 0, r5
  blr
  #_ REGISTER_OUT r3 0x8000000000000001
  #_ MEMORY_OUT 10001010 01000000 00000080 CCCCCCCC

test_stdbrx_roundtrip:
  #_ MEMORY_IN 10001020 00000000 00000000
  #_ REGISTER_IN r3 0x1122334455667788
  #_ REGISTER_IN r4 0x10001020
  stdbrx r3, 0, r4
  ld r6, 0(r4)
  ldbrx r7, 0, r4
  blr
  #_ REGISTER_OUT r6 0x8877665544332211
  #_ REGISTER_OUT r7 0x1122334455667788
