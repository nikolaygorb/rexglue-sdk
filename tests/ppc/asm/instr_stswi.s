test_stswi_lswi_roundtrip:
  #_ MEMORY_IN 10001000 00000000 00000000 00000000
  #_ REGISTER_IN r3 0x10001000
  #_ REGISTER_IN r5 0x01020304
  #_ REGISTER_IN r6 0x05060708
  #_ REGISTER_IN r7 0x090A0B0C
  stswi r5, r3, 10
  lswi r8, r3, 10
  blr
  #_ REGISTER_OUT r8 0x01020304
  #_ REGISTER_OUT r9 0x05060708
  #_ REGISTER_OUT r10 0x090A0000
