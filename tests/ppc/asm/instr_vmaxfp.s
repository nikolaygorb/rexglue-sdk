test_vmaxfp_1:
  # v3 = [10.0, -10.0, 15.0, -15.0]
  # v4 = [-10.0, 20.0, -20.0, 30.0]
  #_ REGISTER_IN v3 [41200000, C1200000, 41700000, C1700000]
  #_ REGISTER_IN v4 [C1200000, 41A00000, C1A00000, 41F00000]
  vmaxfp v0, v3, v4
  blr
  #_ REGISTER_OUT v0 [41200000, 41A00000, 41700000, 41F00000]
  #_ REGISTER_OUT v3 [41200000, C1200000, 41700000, C1700000]
  #_ REGISTER_OUT v4 [C1200000, 41A00000, C1A00000, 41F00000]

test_vmaxfp_nan:
  # NaN in vA, SNaN in vB, both NaN (vA wins, quieted), then +0 against -0
  #_ REGISTER_IN v3 [FFC00000, 00000000, 7FA00000, 00000000]
  #_ REGISTER_IN v4 [00000000, 7F800001, 7FC00002, 80000000]
  vmaxfp v0, v3, v4
  blr
  #_ REGISTER_OUT v0 [FFC00000, 7FC00001, 7FE00000, 00000000]
  #_ REGISTER_OUT v3 [FFC00000, 00000000, 7FA00000, 00000000]
  #_ REGISTER_OUT v4 [00000000, 7F800001, 7FC00002, 80000000]

test_vmaxfp_signed_zero:
  # Signed zeros in both orders
  #_ REGISTER_IN v3 [80000000, 00000000, 3F800000, BF800000]
  #_ REGISTER_IN v4 [00000000, 80000000, BF800000, 3F800000]
  vmaxfp v0, v3, v4
  blr
  #_ REGISTER_OUT v0 [00000000, 00000000, 3F800000, 3F800000]
  #_ REGISTER_OUT v3 [80000000, 00000000, 3F800000, BF800000]
  #_ REGISTER_OUT v4 [00000000, 80000000, BF800000, 3F800000]
