"""Generates the Direct3D 11 backend's copies of Direct3D 12 code.

Some DXBC generators of the D3D12 backend are needed by the D3D11 backend too.
They are not moved into shared files (that would change canary's layout of the
D3D12 sources); the D3D11 backend gets generated copies instead. A copy is made
of fixed text (file header, includes, the class around the code) and regions
cut from the original between unique markers, with a few fixed replacements.
When a canary port changes an original, running this script brings the copy
along; if a marker is gone, the script stops and names it.

Usage:
  python tools/d3d11/sync_copies.py           rewrite the copies
  python tools/d3d11/sync_copies.py --check   exit 1 if a copy is out of date
                                              (CTest: unit.d3d11_copies_in_sync)
"""

