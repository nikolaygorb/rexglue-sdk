def cut(source, start, end, within=None, include_end=True, replacements=()):
    """A region of `source`: from `start` up to `end` (the first one after
    `start`), both searched after `within` if given."""
    return {'source': source, 'start': start, 'end': end, 'within': within,
            'include_end': include_end, 'replacements': replacements}


def function(source, signature, replacements=()):
    """A whole function definition: from its signature line to the first line
    that is a lone `}`."""
    return cut(source, '\n' + signature, '\n}\n', replacements=replacements)


