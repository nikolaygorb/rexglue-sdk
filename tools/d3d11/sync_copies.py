def read_source(path, cache):
    if path not in cache:
        with open(os.path.join(REPO_ROOT, path), encoding='utf-8') as f:
            cache[path] = f.read().replace('\r\n', '\n')
    return cache[path]


def extract(part, cache):
    text = read_source(part['source'], cache)
    origin = 0
    if part['within']:
        origin = text.find(part['within'])
        if origin < 0:
            raise RuntimeError('%s: not found: %r' % (part['source'], part['within']))
    start = text.find(part['start'], origin)
    if start < 0:
        raise RuntimeError('%s: start marker not found: %r' % (part['source'], part['start']))
    if part['start'].startswith('\n'):
        start += 1
    end = text.find(part['end'], start + 1)
    if end < 0:
        raise RuntimeError('%s: end marker not found: %r' % (part['source'], part['end']))
    if part['include_end']:
        end += len(part['end'])
    region = text[start:end]
    for old, new in part['replacements']:
        region = region.replace(old, new)
    return region


def generate(copy, cache):
    return ''.join(part if isinstance(part, str) else extract(part, cache)
                   for part in copy['parts'])


def clang_format(text, target):
    # Formatted like the rest of the tree, so a clang-format run over the
    # sources leaves the copies as they are.
    tool = shutil.which('clang-format')
    if not tool:
        raise RuntimeError('clang-format not found on PATH')
    return subprocess.run([tool, '--style=file:' + os.path.join(REPO_ROOT, '.clang-format'),
                           '--assume-filename=' + os.path.join(REPO_ROOT, target)],
                          input=text, capture_output=True, text=True, encoding='utf-8',
                          check=True).stdout


def main():
    check = '--check' in sys.argv[1:]
    cache = {}
    stale = []
    for copy in COPIES:
        text = clang_format(generate(copy, cache), copy['target'])
        path = os.path.join(REPO_ROOT, copy['target'])
        current = None
        if os.path.exists(path):
            with open(path, encoding='utf-8') as f:
                current = f.read().replace('\r\n', '\n')
        if current == text:
            continue
        if check:
            stale.append(copy['target'])
        else:
            with open(path, 'w', encoding='utf-8', newline='\n') as f:
                f.write(text)
            print('wrote ' + copy['target'])
    if stale:
        print('Out of date (a D3D12 original changed): ' + ', '.join(stale))
        print('Run: python tools/d3d11/sync_copies.py')
        return 1
    if check:
        print('D3D11 copies are up to date')
    return 0


if __name__ == '__main__':
    sys.exit(main())
